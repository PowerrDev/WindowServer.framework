/**
 * File:        crates/windowserver/src/font.rs
 *
 * Bitmap font primitives for WindowServer.
 *
 * This module provides a fixed-size bitmap font abstraction suitable
 * for framebuffer rendering. Glyph data is stored as one bit per pixel and
 * can be consumed directly by the software compositor.
 */

use crate::{
    geometry::Point,
    surface::Surface,
};

// A single bitmap glyph.
//
// Glyph rows are stored consecutively. Each bit represents one pixel:
//
// - 1 = foreground pixel
// - 0 = transparent/background pixel
//
// Bits are read from most-significant to least-significant.
#[derive(Clone, Copy)]
pub struct Glyph {
    data: &'static [u8],
    width: u32,
    height: u32,
    stride: u32,
}

impl Glyph {
    // Creates a bitmap glyph.
    //
    // `stride` is measured in bytes per row.
    pub const fn new(
        data: &'static [u8],
        width: u32,
        height: u32,
        stride: u32,
    ) -> Self {
        Self {
            data,
            width,
            height,
            stride,
        }
    }

    // Returns the glyph width in pixels.
    pub const fn width(&self) -> u32 {
        self.width
    }

    // Returns the glyph height in pixels.
    pub const fn height(&self) -> u32 {
        self.height
    }

    // Returns whether a pixel is set.
    //
    // Returns false when the coordinates are outside the glyph.
    pub fn pixel(&self, x: u32, y: u32) -> bool {
        if x >= self.width || y >= self.height {
            return false;
        }

        let byte_index =
            (y as usize * self.stride as usize)
            + (x as usize / 8);

        let Some(byte) = self.data.get(byte_index) else {
            return false;
        };

        let bit = 7 - (x % 8);

        (byte & (1 << bit)) != 0
    }

    // Draws the glyph onto a surface.
    //
    // Set bits are rendered using `foreground`.
    // Unset bits remain transparent.
    pub fn draw(
        &self,
        surface: &mut Surface<'_>,
        position: Point,
        foreground: u32,
    ) {
        surface.draw_bitmap_1bpp(
            position,
            self.width,
            self.height,
            self.data,
            self.stride,
            foreground,
        );
    }
}

// Fixed-size bitmap font.
//
// The font stores glyphs sequentially. Each glyph occupies the same amount
// of memory and has identical dimensions.
#[derive(Clone, Copy)]
pub struct BitmapFont {
    data: &'static [u8],
    glyph_width: u32,
    glyph_height: u32,
    glyph_stride: u32,
    glyph_size: u32,
    first_char: u8,
    glyph_count: u32,
}

impl BitmapFont {
    // Creates a fixed-size bitmap font.
    //
    // `glyph_stride` is the number of bytes in one glyph row.
    // `glyph_size` is the total number of bytes occupied by one glyph.
    pub const fn new(
        data: &'static [u8],
        glyph_width: u32,
        glyph_height: u32,
        glyph_stride: u32,
        glyph_size: u32,
        first_char: u8,
        glyph_count: u32,
    ) -> Self {
        Self {
            data,
            glyph_width,
            glyph_height,
            glyph_stride,
            glyph_size,
            first_char,
            glyph_count,
        }
    }

    // Returns the width of every glyph.
    pub const fn glyph_width(&self) -> u32 {
        self.glyph_width
    }

    // Returns the height of every glyph.
    pub const fn glyph_height(&self) -> u32 {
        self.glyph_height
    }

    // Returns the first supported character.
    pub const fn first_char(&self) -> u8 {
        self.first_char
    }

    // Returns the number of glyphs.
    pub const fn glyph_count(&self) -> u32 {
        self.glyph_count
    }

    // Looks up a glyph by byte value.
    pub fn glyph(
        &self,
        character: u8,
    ) -> Option<Glyph> {
        if character < self.first_char {
            return None;
        }

        let index =
            (character - self.first_char) as u32;

        if index >= self.glyph_count {
            return None;
        }

        let offset =
            (index as usize)
                .checked_mul(self.glyph_size as usize)?;

        let end =
            offset.checked_add(
                self.glyph_size as usize,
            )?;

        let data =
            self.data.get(offset..end)?;

        Some(Glyph::new(
            data,
            self.glyph_width,
            self.glyph_height,
            self.glyph_stride,
        ))
    }

    // Returns the glyph for a character, falling back to `?`.
    pub fn glyph_or_fallback(
        &self,
        character: u8,
    ) -> Option<Glyph> {
        self.glyph(character)
            .or_else(|| self.glyph(b'?'))
    }
}

